#!/usr/bin/env node
// Bootstrap path for PlatformUser accounts — the platform-plane equivalent
// of scripts/create-admin-user.mjs. There is deliberately no web route
// that creates or first-time-configures a PlatformUser: TOTP is mandatory
// from day one (src/lib/platform-auth.ts's authorize() hard-blocks login
// for any row with totpSecret/totpConfirmedAt unset), and an
// unauthenticated "set up your platform 2FA" HTTP endpoint would itself be
// a way to defeat that mandate. So the two-step setup below happens
// out-of-band, over a shell someone already has to have privileged access
// to reach.
//
// Usage:
//   node scripts/create-platform-user.mjs create <email> <password> <name> [role]
//     role defaults to PLATFORM_SUPPORT. One of PLATFORM_OWNER | PLATFORM_SUPPORT.
//     Prints an otpauth:// URI — add it to an authenticator app (scan as a
//     QR code via any otpauth:// -> QR tool, or use its secret= param for
//     manual entry), THEN run the confirm step below with a live code.
//     The account CANNOT log in until confirm succeeds.
//
//   node scripts/create-platform-user.mjs confirm <email> <6-digit-code>
//     Verifies the code against the secret generated by `create`, and only
//     on success sets totpConfirmedAt — the flag platform-auth.ts's
//     authorize() actually checks.

import { PrismaClient } from "@prisma/client";
import bcrypt from "bcryptjs";
import * as OTPAuth from "otpauth";

const db = new PrismaClient();
const [, , mode, ...rest] = process.argv;

function fail(message) {
  console.error(message);
  process.exitCode = 1;
}

async function createUser() {
  const [email, password, name, role = "PLATFORM_SUPPORT"] = rest;
  if (!email || !password || !name) {
    return fail("Usage: node scripts/create-platform-user.mjs create <email> <password> <name> [role]");
  }
  if (password.length < 8) {
    return fail("Password must be at least 8 characters.");
  }
  if (!["PLATFORM_OWNER", "PLATFORM_SUPPORT"].includes(role)) {
    return fail("role must be one of PLATFORM_OWNER, PLATFORM_SUPPORT");
  }

  const passwordHash = await bcrypt.hash(password, 12);
  // Fresh secret every time `create` runs (including re-running against an
  // existing email) — an upsert that reused an old secret across a
  // password reset would let a stale, possibly-exposed secret keep working
  // silently. totpConfirmedAt is explicitly cleared here for the same
  // reason: a re-run of `create` must always be followed by a fresh
  // `confirm` before the account can log in again.
  const totpSecret = new OTPAuth.Secret({ size: 20 }).base32;

  const user = await db.platformUser.upsert({
    where: { email },
    create: { email, passwordHash, name, role, totpSecret, totpConfirmedAt: null },
    update: { passwordHash, name, role, totpSecret, totpConfirmedAt: null },
  });

  const uri = new OTPAuth.TOTP({
    issuer: "Algo PBX Platform",
    label: email,
    algorithm: "SHA1",
    digits: 6,
    period: 30,
    secret: OTPAuth.Secret.fromBase32(totpSecret),
  }).toString();

  console.log(`Upserted platform user ${user.email} (${user.role}), id=${user.id}`);
  console.log("");
  console.log("Add this to an authenticator app, then confirm with a live code:");
  console.log(uri);
  console.log("");
  console.log(`  node scripts/create-platform-user.mjs confirm ${email} <6-digit-code>`);
  console.log("");
  console.log("This account CANNOT sign in until the confirm step succeeds.");
}

async function confirmTotp() {
  const [email, code] = rest;
  if (!email || !code) {
    return fail("Usage: node scripts/create-platform-user.mjs confirm <email> <6-digit-code>");
  }
  const user = await db.platformUser.findUnique({ where: { email } });
  if (!user || !user.totpSecret) {
    return fail(`No pending TOTP setup found for ${email}. Run 'create' first.`);
  }
  const totp = new OTPAuth.TOTP({
    issuer: "Algo PBX Platform",
    algorithm: "SHA1",
    digits: 6,
    period: 30,
    secret: OTPAuth.Secret.fromBase32(user.totpSecret),
  });
  if (totp.validate({ token: code.trim(), window: 1 }) === null) {
    return fail("Invalid code. Check your device's clock and try again.");
  }
  await db.platformUser.update({ where: { email }, data: { totpConfirmedAt: new Date() } });
  console.log(`TOTP confirmed for ${email}. This account can now sign in at /platform/login.`);
}

if (mode === "create") {
  await createUser();
} else if (mode === "confirm") {
  await confirmTotp();
} else {
  fail(
    "Usage:\n" +
      "  node scripts/create-platform-user.mjs create <email> <password> <name> [role]\n" +
      "  node scripts/create-platform-user.mjs confirm <email> <6-digit-code>"
  );
}

await db.$disconnect();
